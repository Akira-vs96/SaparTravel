export function translate(lang, key) {
  return strings[key]?.[LANGUAGES.indexOf(lang)] ?? key;
}
export const localeFor = (lang) =>
  ({ ru: "ru-RU", kk: "kk-KZ", en: "en-US" })[lang];
export const money = (amount, lang = "ru") =>
  new Intl.NumberFormat(localeFor(lang), {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(amount);
export const formatDate = (value, lang = "ru") =>
  new Intl.DateTimeFormat(localeFor(lang), {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(value));
